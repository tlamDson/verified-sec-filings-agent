"""Resume bullets (What / How / Design / Impact). Every number is a runs.csv value."""

from collections.abc import Sequence

from sec_agent.report.format import show_interval, show_value
from sec_agent.report.latest import latest_rows
from sec_agent.runs import RunRow


class MissingRunError(LookupError):
    """A bullet needs a measured row that runs.csv does not have."""


def _find(rows: Sequence[RunRow], metric: str, system: str) -> RunRow:
    for row in rows:
        if row.metric == metric and row.system == system:
            return row
    raise MissingRunError(f"runs.csv has no row for {metric} / {system}")


def _full(row: RunRow) -> str:
    return f"{show_value(row)} ({show_interval(row)}, n={row.n})"


def render_bullets(rows: Sequence[RunRow]) -> str:
    latest = latest_rows(rows)
    n_agent = _find(latest, "N1", "b2")
    n_base = _find(latest, "N1", "b0")
    a_agent = _find(latest, "A1", "agent")
    a_rag = _find(latest, "A1", "rag")
    s_open = _find(latest, "S1_indirect_success", "none")
    s_guard = _find(latest, "S1_indirect_success", "guarded")
    r_base = _find(latest, "R1_ndcg@10", "hybrid")
    r_ft = _find(latest, "R1_ndcg@10", "hybrid+rerank-ft")
    return f"""# Resume bullets

Generated by `sec-agent report sync`. Every number is a row of `runs.csv`; keep the
`n` and the interval when you quote one. Safety numbers are on synthetic data
(simulated passages), and no real or simulated user numbers exist yet.

## Numbers from tools, not the model

- What: built a research agent over SEC 10-K, 10-Q and XBRL filings where every number
  in an answer traces to a deterministic tool or a cited passage.
- How: on the numeric test questions the agent answered {show_value(n_agent)} correctly
  ({show_interval(n_agent)}, n={n_agent.n}) against {show_value(n_base)} for the same local
  model alone (n={n_base.n}); on the agent scenarios {_full(a_agent)} against
  {_full(a_rag)} for plain retrieval-augmented generation.
- Design: XBRL lookups and ratio code produce the figures, an output checker blocks any
  figure it cannot trace, and the tools resolve fiscal periods and restatements by fixed rules.
- Impact: the answer is the tool's number or no number, so a wrong figure shows up as a
  failed check, not as fluent text.

## Retrieval

- What: hybrid search (vector, BM25, rank fusion in SQL) with a fine-tuned cross-encoder reranker.
- How: nDCG@10 on held-out companies rose from {_full(r_base)} to {_full(r_ft)}.
- Design: the reranker trains by company-held-out folds and falls back to the hybrid order
  when it is slow or down.
- Impact: a measured gain with paired intervals, kept because it beat the baseline.

## Guardrails

- What: guardrails against instructions hidden in filing text.
- How: on the synthetic red-team set (simulated passages) indirect injection succeeded in
  {_full(s_open)} of cases without guardrails and {_full(s_guard)} with them.
- Design: instruction sentences in filing text are quarantined, a canary is planted in the
  prompt, and the tools are read-only.
- Impact: an attack-success rate with an interval, on synthetic data only.
"""
